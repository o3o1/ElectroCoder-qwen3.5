# 4. 主控引擎：无限循环挂机，直达 1000 条
# ==========================================
def get_current_dataset_size(filepath="pe_dataset.jsonl"):
    """读取当前已经存了多少条数据，支持断点续传"""
    if not os.path.exists(filepath):
        return 0
    with open(filepath, "r", encoding="utf-8") as f:
        return sum(1 for line in f if line.strip())


async def main():
    TARGET_DATA_COUNT = 1000
    DATASET_FILE = "pe_dataset.jsonl"

    current_count = get_current_dataset_size(DATASET_FILE)
    print(f"🔥 大创全自动数据合成流水线启动！当前已有数据: {current_count} / {TARGET_DATA_COUNT}")

    while current_count < TARGET_DATA_COUNT:
        try:
            client = OpenAIChatClient()

            # 1. 智能体 A 自动出题
            task = await brainstorm_new_task(client)
            if not task:
                print("  ⚠️ 出题格式异常，丢弃重试...")
                continue

            print(f"  📝 新专业题目出炉:\n  {task['instruction'][:150]}...\n  🚀 验证命令: {task['check_cmd']}")

            # 2. 智能体 B 做题并验证 (放宽到 600 秒超时，给足多轮修 Bug 和网络请求的时间)
            data = await asyncio.wait_for(
                generate_data(task["instruction"], task["file_path"], task["check_cmd"]),
                timeout=600.0
            )

            # 3. 如果做题成功，写入文件并计数
            if data:
                with open(DATASET_FILE, "a", encoding="utf-8") as f:
                    f.write(json.dumps(data, ensure_ascii=False) + "\n")
                current_count += 1
                print(
                    f"🎉 进度更新: 成功保存第 {current_count} / {TARGET_DATA_COUNT} 条高质量严谨测试数据！\n" + "=" * 60)
            else:
                print("🔄 没关系，抛弃这题，准备生成下一题。\n" + "=" * 60)

        except asyncio.TimeoutError:
            print("⏰ [系统] 这道题花费时间超过了 10 分钟 (API延迟或陷入死循环)，为了效率强制跳过！\n" + "=" * 60)
        except Exception as e:
            print(f"❌[系统] 发生意外崩溃: {str(e)}，稍后自动重试...\n" + "=" * 60)
            await asyncio.sleep(2)

    print(f"\n🏆 恭喜！{TARGET_DATA_COUNT} 条真实跑通的电力电子代码数据集已全部生成完毕！")


if __name__ == "__main__":
    asyncio.run(main())