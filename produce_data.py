@tool(approval_mode="never_require")
def write_code_file(
        file_path: Annotated[str, Field(description="保存代码的本地路径")],
        content: Annotated[str, Field(description="要保存的完整代码内容")]
) -> str:
    try:
        os.makedirs(os.path.dirname(file_path), exist_ok=True)
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)
        return f"[Success] 文件已写入: {file_path}"
    except Exception as e:
        return f"[Error] 写入失败: {str(e)}"


@tool(approval_mode="never_require")
def execute_command(command: Annotated[str, Field(description="在终端运行的命令")]) -> str:
    try:
        # 工具层面限制单次运行最多15秒，防止C代码里写了死循环(while(1))导致系统卡死
        result = subprocess.run(
            command, shell=True, capture_output=True, text=True, errors="replace", timeout=15
        )
        if result.returncode == 0:
            return f"[Success] 运行通过。\n输出:\n{result.stdout}"
        else:
            return f"[Error] 运行失败。\n错误信息:\n{result.stderr}\n{result.stdout}"
    except subprocess.TimeoutExpired:
        return "[Error] 运行超时(超过15秒)，说明你的C代码存在死循环或等待输入，请修改代码！"
    except Exception as e:
        return f"[Error] 系统异常: {str(e)}"


