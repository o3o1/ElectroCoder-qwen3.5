async def generate_data(instruction: str, file_path: str, check_cmd: str, max_turns=6):
    client = OpenAIChatClient()
    agent = Agent(
        client=client,
        name="PowerElectronics_Solver",
        instructions=(
            "你是顶尖的电力电子专家。\n"
            "【效率与核心规则】：\n"
            "1. 闭嘴法则：不要做任何解释！不要说废话！不要使用 markdown 输出代码！\n"
            "2. 拿到需求后，必须立即、直接调用 `write_code_file` 工具保存代码。\n"
            "3. 保存后必须立刻调用 `execute_command` 工具运行验证。\n"
            "4. 如果报错，继续静默修正代码并调用工具验证，直到成功。\n"
            "5. 只有当你看到工具返回 [Success] 时，回复四个字 '验证通过'。"
        ),
        tools=[write_code_file, execute_command]
    )

    current_prompt = f"任务: {instruction}\n请立即调用 `write_code_file` 存入'{file_path}'并用 `execute_command` 执行'{check_cmd}'。"

    for i in range(max_turns):
        print(f"  ⏳ [做题老师] 第 {i + 1} 轮：写代码与真实环境运行调试中...")
        response = await agent.run(current_prompt)
        reply_text = str(response)

        # 防止模型不调工具直接输出了文本代码
        if "```c" in reply_text or "```cpp" in reply_text:
            current_prompt = "严重警告：你违反了闭嘴法则！请务必只调用 `write_code_file` 工具保存代码，否则我无法进行物理环境的编译验证！"
            continue

        # 判定成功：模型说通过，且文件确实生成了
        if "验证通过" in reply_text or "[Success]" in reply_text:
            if os.path.exists(file_path):
                print("  ✅ [做题老师] 搞定！代码已完美通过真实环境编译与运行测试。")
                with open(file_path, "r", encoding="utf-8") as f:
                    return {"instruction": instruction, "output": f.read()}
            else:
                current_prompt = "未找到物理文件，发生幻觉。请重新调用工具保存。"
                continue

        # 查错逻辑：把报错信息喂回去
        current_prompt = "请仔细检查刚才环境返回的运行结果。如有错误继续修正并调用工具验证；如果确实完全成功无错，请回复'验证通过'。"

    print("  ❌ 达到最大修正次数，说明该题太难或死循环，本题放弃。")
    return None


